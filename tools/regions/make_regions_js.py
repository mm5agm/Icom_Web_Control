"""Makes core/js/spotmap/region-data.js: state and province outlines for the
Spot Map, from Natural Earth's 1:50m admin-1 file (public domain,
https://www.naturalearthdata.com/). It covers the USA, Canada, Australia,
Russia, Brazil, China, India, Indonesia and South Africa.

    curl -L -o ne.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_1_states_provinces.geojson
    python make_regions_js.py ne.geojson ../../js/spotmap/region-data.js

Each region is one line: country|abbreviation|name|label lat|label lon|rings.
Rings are separated by ';'. A ring is lon,lat pairs in hundredths of a degree
(about 1 km), the first pair absolute and the rest as differences.
"""
import json, sys

STEP = 100          # hundredths of a degree
TOL = 0.03          # simplify: drop points closer than this (degrees) to the line


def simplify(pts, tol):
    """Ramer-Douglas-Peucker, iterative."""
    if len(pts) < 4:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1
        L2 = dx * dx + dy * dy
        best, at = 0.0, -1
        for i in range(a + 1, b):
            x, y = pts[i]
            if L2 == 0:
                d = (x - x1) ** 2 + (y - y1) ** 2
            else:
                t = max(0, min(1, ((x - x1) * dx + (y - y1) * dy) / L2))
                d = (x - x1 - t * dx) ** 2 + (y - y1 - t * dy) ** 2
            if d > best:
                best, at = d, i
        if at >= 0 and best > tol * tol:
            keep[at] = True
            stack += [(a, at), (at, b)]
    return [p for p, k in zip(pts, keep) if k]


def ring_code(ring):
    pts = simplify([(x, y) for x, y in ring], TOL)
    ints = []
    for x, y in pts:
        p = (round(x * STEP), round(y * STEP))
        if not ints or ints[-1] != p:
            ints.append(p)
    if len(ints) < 4:
        return None
    out, px, py = [], 0, 0
    for i, (x, y) in enumerate(ints):
        out += [x - px, y - py] if i else [x, y]
        px, py = x, y
    return ','.join(map(str, out))


def main(src, dst):
    feats = json.load(open(src, encoding='utf-8'))['features']
    lines = []
    for f in sorted(feats, key=lambda f: (f['properties']['iso_a2'], f['properties']['name'] or '')):
        p, g = f['properties'], f['geometry']
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        rings = [c for poly in polys for c in [ring_code(poly[0])] if c]   # outer rings only
        if not rings:
            continue
        name = (p['name'] or p.get('name_en') or '').replace('|', ' ')
        # The ISO 3166-2 code (US-TX -> TX, AU-NSW -> NSW); Natural Earth's own
        # 'postal' field has odd ones for Australia (NS, QL, VI).
        iso = (p.get('iso_3166_2') or '').split('-')
        abbr = (iso[1] if len(iso) == 2 and iso[1].isalpha() else p.get('postal') or '').replace('|', ' ')
        lines.append(f"{p['iso_a2']}|{abbr}|{name}|{p['latitude']:.2f}|{p['longitude']:.2f}|{';'.join(rings)}")
    with open(dst, 'w', encoding='utf-8', newline='\r\n') as o:
        o.write("// Generated by core/tools/regions/make_regions_js.py from Natural Earth's\n"
                "// 1:50m admin-1 states and provinces (public domain). Do not edit by hand.\n"
                "// One region per line: country|abbreviation|name|label lat|label lon|rings.\n"
                "export const REGIONS = `\n" + '\n'.join(lines) + "\n`;\n")
    print(len(lines), 'regions')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
